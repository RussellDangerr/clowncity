  getTilesNear(px, py, pw, ph) {
    // Spatial grid lookup — O(1) per cell instead of O(n) scan
    const s = this.tileSize;
    const x1 = Math.floor((px - s) / s);
    const x2 = Math.floor((px + pw + s) / s);
    const y1 = Math.floor((py - s) / s);
    const y2 = Math.floor((py + ph + s) / s);
    const result = [];
    for (let gy = y1; gy <= y2; gy++) {
      for (let gx = x1; gx <= x2; gx++) {
        if (this.wrap) {
          // Fold the column onto the map, then move the tile to where it sits
          // on this lap, so the collision maths sees it beside Poko.
          const wx = this._wrapCol(gx);
          const tile = this._tileGrid[wx + ',' + gy];
          if (tile && !tile.broken) result.push(wx === gx ? tile : Object.assign({}, tile, { x: tile.x + (gx - wx) * s }));
          continue;
        }
        const tile = this._tileGrid[gx + ',' + gy];
        if (tile && !tile.broken) result.push(tile);
      }
    }
    return result;
  },

  // Surface (top) Y of a slope tile at a world X. Linear for 45°.
  //   '/' (slopeDir +1): low at the left edge, high at the right.
  //   '\' (slopeDir -1): high at the left edge, low at the right.
  slopeSurfaceY(tile, worldX) {
    const s = this.tileSize;
    const localX = Math.max(0, Math.min(s, worldX - tile.x));
    return tile.slopeDir > 0 ? tile.y + (s - localX) : tile.y + localX;
  },

  // ── Curved ramps ──
  // A ramp is a cubic Hermite curve through [tileX, tileY, slope] points, where
  // slope = dy/dx on screen (+ = downhill to the right, ±1 = 45°). Each point
  // pins the height AND the angle there, so a ramp can leave flat ground
  // tangentially and end on a lip at exactly the launch angle wanted.
  rampAt(x) {
    for (const r of this.ramps || []) if (x >= r.x0 && x <= r.x1) return r;
    return null;
  },

  _rampSeg(r, x) {
    let i = 0;
    while (i < r.pts.length - 2 && x > r.pts[i + 1].x) i++;
    const a = r.pts[i], b = r.pts[i + 1], h = b.x - a.x;
    return { a, b, h, t: (x - a.x) / h };
  },

  rampY(r, x) {
    const { a, b, h, t } = this._rampSeg(r, x);
    const t2 = t * t, t3 = t2 * t;
    return (2 * t3 - 3 * t2 + 1) * a.y + (t3 - 2 * t2 + t) * h * a.m
         + (-2 * t3 + 3 * t2) * b.y + (t3 - t2) * h * b.m;
  },

  rampSlope(r, x) {
    const { a, b, h, t } = this._rampSeg(r, x);
    const t2 = t * t;
    return ((6 * t2 - 6 * t) * a.y + (3 * t2 - 4 * t + 1) * h * a.m
          + (-6 * t2 + 6 * t) * b.y + (3 * t2 - 2 * t) * h * b.m) / h;
  },

  // Begin a path along a ramp's surface, sampled every 4px.
  _traceRamp(ctx, r) {
    ctx.beginPath();
    ctx.moveTo(r.x0, this.rampY(r, r.x0));
    for (let x = r.x0 + 4; x < r.x1; x += 4) ctx.lineTo(x, this.rampY(r, x));
    ctx.lineTo(r.x1, this.rampY(r, r.x1));
  },

  getSlopesNear(px, py, pw, ph) {
    if (!this._slopeGrid) return [];
    const s = this.tileSize;
    const x1 = Math.floor((px - s) / s), x2 = Math.floor((px + pw + s) / s);
    const y1 = Math.floor((py - s) / s), y2 = Math.floor((py + ph + s) / s);
    const result = [];
    for (let gy = y1; gy <= y2; gy++) {
      for (let gx = x1; gx <= x2; gx++) {
        const t = this._slopeGrid[gx + ',' + gy];
        if (t) result.push(t);
      }
    }
    return result;
  },

